-- ============================================================

-- =========================
-- 1. Tabla principal
-- =========================

create table if not exists public.agencies (
  id uuid primary key default gen_random_uuid(),

  owner_user_id uuid not null unique
    references public.profiles(id)
    on delete cascade,

  agency_name text not null,
  commercial_name text not null,

  business_type text not null
    check (
      business_type in (
        'AGENCY',
        'TOUR_OPERATOR',
        'TRANSPORT',
        'INDEPENDENT_GUIDE'
      )
    ),

  description text,

  email text,
  phone text,
  website text,

  country text,
  province text,
  city text,
  exact_address text,

  logo_url text,
  cover_url text,
  verification_document_url text,

  instagram_url text,
  facebook_url text,
  whatsapp text,

  status text not null default 'DRAFT'
    check (
      status in (
        'DRAFT',
        'PENDING',
        'APPROVED',
        'REJECTED',
        'INACTIVE'
      )
    ),

  accepted_terms boolean not null default false,
  terms_accepted_at timestamptz,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Mantiene updated_at actualizado automáticamente.
create trigger agencies_set_updated_at
before update on public.agencies
for each row execute procedure public.set_updated_at();


-- =========================
-- 2. Categorías de servicio
-- =========================

create table if not exists public.service_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now()
);


-- =========================
-- 3. Relación agencia-categoría
-- =========================

create table if not exists public.agency_service_categories (
  agency_id uuid not null
    references public.agencies(id)
    on delete cascade,

  category_id bigint not null
    references public.service_categories(id)
    on delete cascade,

  primary key (agency_id, category_id)
);


-- =========================
-- 4. Idiomas
-- =========================

create table if not exists public.languages (
  id bigint generated by default as identity primary key,
  name text not null unique,
  code text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now()
);


-- =========================
-- 5. Relación agencia-idioma
-- =========================

create table if not exists public.agency_languages (
  agency_id uuid not null
    references public.agencies(id)
    on delete cascade,

  language_id bigint not null
    references public.languages(id)
    on delete cascade,

  primary key (agency_id, language_id)
);


-- =========================
-- 6. Datos iniciales
-- =========================

insert into public.service_categories (name)
values
  ('Aventura'),
  ('Naturaleza'),
  ('Cultura'),
  ('Transporte'),
  ('Playa'),
  ('Bienestar')
on conflict (name) do nothing;

insert into public.languages (name, code)
values
  ('Español', 'es'),
  ('Inglés', 'en')
on conflict (code) do nothing;


-- =========================
-- 7. Índices
-- =========================

create index if not exists idx_agencies_status
  on public.agencies(status);

create index if not exists idx_agencies_business_type
  on public.agencies(business_type);

create index if not exists idx_agency_categories_agency
  on public.agency_service_categories(agency_id);

create index if not exists idx_agency_languages_agency
  on public.agency_languages(agency_id);


-- =========================
-- 8. Seguridad
-- =========================

alter table public.agencies enable row level security;
alter table public.service_categories enable row level security;
alter table public.agency_service_categories enable row level security;
alter table public.languages enable row level security;
alter table public.agency_languages enable row level security;

-- El acceso a estas tablas se realizará mediante las rutas /api
-- usando el cliente seguro del servidor.
revoke all on table public.agencies from anon, authenticated;
revoke all on table public.service_categories from anon, authenticated;
revoke all on table public.agency_service_categories from anon, authenticated;
revoke all on table public.languages from anon, authenticated;
revoke all on table public.agency_languages from anon, authenticated;