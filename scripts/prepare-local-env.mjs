import fs from 'node:fs';
import { parseEnv } from 'node:util';

// Cloudflare ignores .env files when .dev.vars exists. Keep local server
// bindings synchronized without copying secrets into tracked configuration.
const values = {};
for (const file of ['.env', '.env.development', '.env.local', '.env.development.local']) {
  if (fs.existsSync(file)) Object.assign(values, parseEnv(fs.readFileSync(file, 'utf8')));
}
const entries = Object.entries(values).filter(([key]) =>
  /^(SUPABASE_|NEXT_PUBLIC_SUPABASE_|SMTP_|MAIL_|ONVO_)/.test(key)
  || ['GEOAPIFY_API_KEY', 'LARUTICA_REMOTE_API_ORIGIN', 'DEEPSEEK_API_KEY'].includes(key));
const content = '# Generated by scripts/prepare-local-env.mjs. Edit .env.local instead.\n'
  + entries.map(([key,value]) => `${key}=${JSON.stringify(value)}`).join('\n') + '\n';
fs.writeFileSync('.dev.vars', content, { mode: 0o600 });
console.log('Variables locales preparadas para el servidor; los valores privados no se muestran.');
